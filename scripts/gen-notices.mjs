#!/usr/bin/env node
// Generate THIRD-PARTY-NOTICES from Cargo.lock.
//
// Every crate the lock pins is listed with the license its manifest declares, fetched from the
// crates.io API for that exact version. The lock also pins target-specific crates (for example,
// wasm32 only), so the list is a superset of what a given binary links. Network access is only
// needed when the file is regenerated; the release workflow runs this and ships the result.

import fs from 'node:fs';

const lockPath = process.argv[2] ?? 'Cargo.lock';
const outPath = process.argv[3] ?? 'THIRD-PARTY-NOTICES';
const rootName = 'opentune-beats';
const userAgent = 'opentune-beats notices generator (contact@synchain.ca)';

const lock = fs.readFileSync(lockPath, 'utf8');
const crates = [];
for (const block of lock.split('[[package]]').slice(1)) {
  const name = /^name = "([^"]+)"/m.exec(block)?.[1];
  const version = /^version = "([^"]+)"/m.exec(block)?.[1];
  if (!name || !version || name === rootName) continue;
  crates.push({ name, version });
}
crates.sort((left, right) =>
  left.name === right.name ? left.version.localeCompare(right.version) : left.name.localeCompare(right.name),
);

const licenses = new Map();
async function licenseOf(krate) {
  const key = `${krate.name}@${krate.version}`;
  if (!licenses.has(key)) {
    const response = await fetch(`https://crates.io/api/v1/crates/${krate.name}/${krate.version}`, {
      headers: { 'user-agent': userAgent },
    });
    if (!response.ok) throw new Error(`${key}: crates.io answered ${response.status}`);
    const body = await response.json();
    licenses.set(key, body.version.license ?? 'no license declared');
  }
  return licenses.get(key);
}

const lines = [
  'OpenTune Beats — third-party notices',
  '',
  'This file lists the third-party Rust crates pinned in Cargo.lock, with the license each crate',
  'declares. The crates actually linked into a binary are a subset: the lock also pins',
  'target-specific dependencies (for example, wasm32 only). It is generated by',
  'scripts/gen-notices.mjs and ships next to the executable in the release archive, so that a',
  'binary distribution carries the notices it is required to carry.',
  '',
  'Beat This! and beat-this-rs are described in NOTICE.',
  '',
  'Crates',
  '',
];
for (const krate of crates) {
  lines.push(`  ${krate.name} ${krate.version} — ${await licenseOf(krate)}`);
}
lines.push('');
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`wrote ${outPath}: ${crates.length} crates`);
