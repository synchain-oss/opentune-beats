//! SHA-256, for checking a model file before it is loaded.
//!
//! A model is data, not code: the binary only needs to know that the bytes on disk are the bytes
//! the release was built against. The implementation follows FIPS 180-4 and is checked against
//! the standard test vectors.

use std::fmt::Write as _;
use std::fs::File;
use std::io::{self, Read};
use std::path::Path;

const INITIAL: [u32; 8] = [
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
];

